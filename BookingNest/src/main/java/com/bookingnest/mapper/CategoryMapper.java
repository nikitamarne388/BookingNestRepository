package com.bookingnest.mapper;

import com.bookingnest.dto.request.CategoryRequest;
import com.bookingnest.dto.response.AdminCategoryResponse;
import com.bookingnest.dto.response.CategoryResponse;
import com.bookingnest.entity.Category;
import org.mapstruct.Mapper;
import org.mapstruct.Mapping;
import org.mapstruct.MappingTarget;
import org.mapstruct.ReportingPolicy;

import java.util.List;

@Mapper(componentModel = "spring", unmappedTargetPolicy = ReportingPolicy.ERROR)
public interface CategoryMapper {

    /**
     * Create flow. Two fields are deliberately NOT mapped here:
     *  - slug:   generated by the service (SlugGenerator) so it is unique
     *  - parent: the request only carries parentId; the service loads the Category and sets it
     * id / createdAt / updatedAt have no setters (BaseEntity), so MapStruct does not see them as targets.
     */
    @Mapping(target = "slug", ignore = true)
    @Mapping(target = "parent", ignore = true)
    @Mapping(target = "id", ignore = true)
    @Mapping(target = "createdAt", ignore = true)
    @Mapping(target = "updatedAt", ignore = true)
    Category toEntity(CategoryRequest request);

    /**
     * Update flow (PUT): copies the request values onto an already loaded entity.
     * Slug regeneration and parent change are handled in the service.
     */
    @Mapping(target = "slug", ignore = true)
    @Mapping(target = "parent", ignore = true)
    @Mapping(target = "id", ignore = true)
    @Mapping(target = "createdAt", ignore = true)
    @Mapping(target = "updatedAt", ignore = true)
    void updateEntity(CategoryRequest request, @MappingTarget Category category);

    /** Public API response. parent.id becomes parentId (null-safe: MapStruct returns null for a null parent). */
    @Mapping(source = "parent.id", target = "parentId")
    CategoryResponse toResponse(Category category);

    /** Admin API response: also exposes status, parent name and audit timestamps. */
    @Mapping(source = "parent.id", target = "parentId")
    @Mapping(source = "parent.name", target = "parentName")
    AdminCategoryResponse toAdminResponse(Category category);

    /** lists of response for public and Admin */

    List<CategoryResponse> toResponseList(List<Category> categories);

    List<AdminCategoryResponse> toAdminResponseList(List<Category> categories);
}
